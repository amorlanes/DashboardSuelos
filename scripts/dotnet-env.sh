#!/usr/bin/env bash
# Source this file in Linux cloud tasks; it does not change HOME.
export CONSTRUCTORA_TOOLS_ROOT="${CONSTRUCTORA_TOOLS_ROOT:-/workspace}"
export DOTNET_ROOT="$CONSTRUCTORA_TOOLS_ROOT/.dotnet"
export DOTNET_CLI_HOME="$CONSTRUCTORA_TOOLS_ROOT/.dotnet-home"
export NUGET_PACKAGES="$CONSTRUCTORA_TOOLS_ROOT/.nuget/packages"
export XDG_RUNTIME_DIR="${XDG_RUNTIME_DIR:-$CONSTRUCTORA_TOOLS_ROOT/.xdg-runtime}"
export XDG_DATA_HOME="${XDG_DATA_HOME:-$CONSTRUCTORA_TOOLS_ROOT/.xdg-data}"
export XDG_CACHE_HOME="${XDG_CACHE_HOME:-$CONSTRUCTORA_TOOLS_ROOT/.xdg-cache}"
export DOTNET_CLI_TELEMETRY_OPTOUT=1
export DOTNET_NOLOGO=1
export PATH="$DOTNET_ROOT:$PATH"
mkdir -p "$DOTNET_CLI_HOME" "$NUGET_PACKAGES" "$XDG_RUNTIME_DIR" "$XDG_DATA_HOME" "$XDG_CACHE_HOME"
chmod 700 "$XDG_RUNTIME_DIR"
