using Constructora.Application.Bim;
using Microsoft.EntityFrameworkCore;

namespace Constructora.Client.Bim;

public sealed class ModeloBimLocal
{
    public Guid Id { get; set; }
    public Guid ProyectoId { get; set; }
    public string Nombre { get; set; } = string.Empty;
    public DateTime CreadoUtc { get; set; }
    public string? ProyectoIfcGlobalId { get; set; }
}

public sealed class VersionModeloBimLocal
{
    public Guid Id { get; set; }
    public Guid ModeloId { get; set; }
    public int Numero { get; set; }
    public string NombreArchivo { get; set; } = string.Empty;
    public string Sha256 { get; set; } = string.Empty;
    // A basename generated by this service, never the user's source path.
    public string ArchivoArchivado { get; set; } = string.Empty;
    public DateTime ImportadaUtc { get; set; }
    public string ImportacionJson { get; set; } = string.Empty;
}

public sealed class VinculoElementoPartidaBimLocal
{
    public Guid Id { get; set; }
    public Guid ModeloId { get; set; }
    public string GlobalId { get; set; } = string.Empty;
    public Guid PartidaId { get; set; }
    public ReglaMedicionBim Regla { get; set; }
    public decimal Factor { get; set; }
}

// An independent database: BIM setup never migrates or modifies certification tables.
public sealed class BimLocalDbContext(DbContextOptions<BimLocalDbContext> options) : DbContext(options)
{
    public DbSet<ModeloBimLocal> Modelos => Set<ModeloBimLocal>();
    public DbSet<VersionModeloBimLocal> Versiones => Set<VersionModeloBimLocal>();
    public DbSet<VinculoElementoPartidaBimLocal> Vinculos => Set<VinculoElementoPartidaBimLocal>();

    protected override void OnModelCreating(ModelBuilder builder)
    {
        builder.Entity<ModeloBimLocal>(b =>
        {
            b.HasKey(x => x.Id);
            b.Property(x => x.Id).ValueGeneratedNever();
            b.HasIndex(x => x.ProyectoId);
            b.Property(x => x.Nombre).HasMaxLength(255).IsRequired();
        });
        builder.Entity<VersionModeloBimLocal>(b =>
        {
            b.HasKey(x => x.Id);
            b.Property(x => x.Id).ValueGeneratedNever();
            b.HasIndex(x => new { x.ModeloId, x.Numero }).IsUnique();
            b.HasIndex(x => new { x.ModeloId, x.Sha256 }).IsUnique();
            b.HasOne<ModeloBimLocal>().WithMany().HasForeignKey(x => x.ModeloId).OnDelete(DeleteBehavior.Restrict);
            b.Property(x => x.ImportacionJson).IsRequired();
        });
        builder.Entity<VinculoElementoPartidaBimLocal>(b =>
        {
            b.HasKey(x => x.Id);
            b.Property(x => x.Id).ValueGeneratedNever();
            b.HasIndex(x => new { x.ModeloId, x.GlobalId, x.PartidaId }).IsUnique();
            // No FK to a particular revision: deleted elements retain their historical mapping.
            b.HasOne<ModeloBimLocal>().WithMany().HasForeignKey(x => x.ModeloId).OnDelete(DeleteBehavior.Restrict);
            b.Property(x => x.GlobalId).IsRequired().HasMaxLength(255);
            b.Property(x => x.Factor).HasPrecision(18, 6);
        });
    }
}
